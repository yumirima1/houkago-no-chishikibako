import { writeFile } from "node:fs/promises";

import {
  builtEpisodeDir,
  generatedEpisodesFile,
  listJsonFiles,
  readJsonFile,
} from "./episode-fs";
import {
  EpisodeDurationType,
  EpisodeProductionStatus,
  EpisodeType,
} from "./episode-schema";

export type SiteEpisodeMetadata = {
  id: string;
  title: string;
  description: string;
  audioUrl?: string;
  durationType: EpisodeDurationType;
  publishedAt: string;
  duration: string;
  tags: string[];
  themes: string[];
  type: EpisodeType;
  speakers: {
    science: string;
    humanities: string;
  };
  productionStatus: EpisodeProductionStatus;
};

export function toEpisodeSnippet(episode: SiteEpisodeMetadata) {
  const audioLine = episode.audioUrl
    ? `  audioUrl: ${JSON.stringify(episode.audioUrl)},\n`
    : "";

  return `{
  id: ${JSON.stringify(episode.id)},
  title: ${JSON.stringify(episode.title)},
  description: ${JSON.stringify(episode.description)},
${audioLine}  type: ${JSON.stringify(episode.type)},
  durationType: ${JSON.stringify(episode.durationType)},
  publishedAt: ${JSON.stringify(episode.publishedAt)},
  duration: ${JSON.stringify(episode.duration)},
  tags: ${JSON.stringify(episode.tags)},
  themes: ${JSON.stringify(episode.themes)},
  speakers: ${JSON.stringify(episode.speakers, null, 2)},
  productionStatus: ${JSON.stringify(episode.productionStatus)},
}`;
}

export async function writeGeneratedEpisodesFile() {
  const episodeFiles = await listJsonFiles(builtEpisodeDir);
  const episodes = await Promise.all(
    episodeFiles.map((file) => readJsonFile<SiteEpisodeMetadata>(file)),
  );
  const body = episodes
    .map((episode) => `  ${toEpisodeSnippet(episode).replaceAll("\n", "\n  ")},`)
    .join("\n");
  const fileContents = `import type { Episode } from "./episodes";

// This file is generated by episode metadata scripts.
// Edit content/episodes/*.json, then run npm run episode:build or npm run episode:seed.
export const generatedEpisodes: Episode[] = [
${body}
];
`;

  await writeFile(generatedEpisodesFile, fileContents, "utf8");
}
